/* Reusable Help System — app logic
   Renders the explorer tree, wires up search, and drives the detail panel.
   No frameworks, no build step, no network calls — works from a plain
   double-clicked index.html or an in-editor HTML preview.

   Expects two globals to already be defined by assets/content.js, which is
   generated by build_help.py (see that file for why build-time compilation
   is required instead of fetch()'ing the markdown at runtime — fetch() is
   blocked under the file:// origin browsers use for a double-clicked HTML
   file, and this help system is designed to be opened exactly that way):

     HELP_CATEGORIES = [ { id, label, icon, pages: [ { id, title, html } ] } ]
     HELP_CONFIG     = { title, storageKey, defaultTopic, defaultExpanded,
                          features: { slashCommands }, contextMap }
*/

(function () {
  "use strict";

  const treeEl = document.getElementById("tree");
  const detailEl = document.getElementById("detail");
  const breadcrumbEl = document.getElementById("breadcrumb");
  const searchInput = document.getElementById("search-input");
  const searchClear = document.getElementById("search-clear");
  const searchMeta = document.getElementById("search-meta");
  const explorerEl = document.getElementById("explorer");
  const explorerTitleEl = document.getElementById("explorer-title");
  const splitterEl = document.getElementById("splitter");

  // Config is optional-ish: every field has a safe fallback so a hand-edited
  // or partially-generated content.js still produces a working (if generic)
  // help page instead of a blank one.
  const CONFIG = Object.assign(
    {
      title: "Help",
      storageKey: "help",
      defaultTopic: null,
      defaultExpanded: [],
      features: {},
      contextMap: {},
    },
    typeof HELP_CONFIG === "object" && HELP_CONFIG ? HELP_CONFIG : {}
  );
  const SLASH_COMMANDS_ENABLED = !!(CONFIG.features && CONFIG.features.slashCommands);

  // Inject the title in the two places the old reference implementation had
  // it hard-coded, so any project can rebrand this shell purely through the
  // manifest — no HTML/JS edits needed.
  document.title = CONFIG.title;
  if (explorerTitleEl) explorerTitleEl.textContent = CONFIG.title;

  // Flat index of all pages for lookup + search.
  const PAGE_INDEX = new Map(); // key "cat:page" -> { cat, page }
  HELP_CATEGORIES.forEach((cat) => {
    cat.pages.forEach((page) => {
      PAGE_INDEX.set(cat.id + ":" + page.id, { cat, page });
    });
  });

  // Known slash-command names, derived at runtime from the "commands"
  // category's page titles (e.g. "/my-command — Pass 0" -> "my-command").
  // Used to color bare /command mentions wherever they appear in prose or
  // code blocks, not just where they're already wrapped in .badge-command.
  // Entirely opt-in via HELP_CONFIG.features.slashCommands — when disabled
  // (the default) colorizeSlashCommands() below is a complete no-op.
  const commandsCat = SLASH_COMMANDS_ENABLED
    ? HELP_CATEGORIES.find((c) => c.id === "commands")
    : null;
  const SLASH_COMMAND_NAMES = commandsCat
    ? commandsCat.pages
        .map((p) => {
          const m = /^\/([a-z0-9-]+)/.exec(p.title);
          return m ? m[1] : null;
        })
        .filter(Boolean)
    : [];
  const SLASH_COMMAND_RE = SLASH_COMMAND_NAMES.length
    ? new RegExp("(/(?:" + SLASH_COMMAND_NAMES.join("|") + ")\\b)", "g")
    : null;

  let currentKey = null;
  // Categories listed in HELP_CONFIG.defaultExpanded start expanded;
  // everything else begins collapsed. (Previously this list was a single
  // hard-coded category id — see FIX #4 in the project README.)
  const defaultExpandedSet = new Set(CONFIG.defaultExpanded || []);
  let collapsedCategories = new Set(
    HELP_CATEGORIES.filter((cat) => !defaultExpandedSet.has(cat.id)).map((cat) => cat.id)
  );

  function stripHtml(html) {
    const tmp = document.createElement("div");
    tmp.innerHTML = html;
    return tmp.textContent || "";
  }

  function buildTree(filterText) {
    treeEl.innerHTML = "";
    const term = (filterText || "").trim().toLowerCase();
    let totalMatches = 0;
    let matchedPageCount = 0;

    HELP_CATEGORIES.forEach((cat) => {
      const matchingPages = cat.pages.filter((page) => {
        if (!term) return true;
        const haystack = (
          page.title + " " + stripHtml(page.html)
        ).toLowerCase();
        return haystack.includes(term);
      });

      if (term && matchingPages.length === 0) return;

      totalMatches += matchingPages.length;
      matchedPageCount += matchingPages.length;

      const catDiv = document.createElement("div");
      catDiv.className = "category";
      if (collapsedCategories.has(cat.id) && !term) {
        catDiv.classList.add("collapsed");
      }

      const header = document.createElement("div");
      header.className = "category-header";
      header.innerHTML =
        '<span class="category-caret">▾</span>' +
        '<span class="category-icon">' + cat.icon + "</span>" +
        "<span>" + cat.label + "</span>";
      header.addEventListener("click", () => {
        if (term) return; // don't allow collapse while filtering
        catDiv.classList.toggle("collapsed");
        if (catDiv.classList.contains("collapsed")) {
          collapsedCategories.add(cat.id);
        } else {
          collapsedCategories.delete(cat.id);
        }
      });
      catDiv.appendChild(header);

      const list = document.createElement("div");
      list.className = "page-list";

      const pagesToRender = term ? matchingPages : cat.pages;
      pagesToRender.forEach((page) => {
        const key = cat.id + ":" + page.id;
        const item = document.createElement("div");
        item.className = "page-item";
        item.dataset.key = key;
        if (key === currentKey) item.classList.add("active");
        item.innerHTML =
          '<span class="page-icon">📝</span><span class="page-label"></span>';
        item.querySelector(".page-label").textContent = stripHtml(page.title);
        item.addEventListener("click", () => navigateTo(key, term));
        list.appendChild(item);
      });

      catDiv.appendChild(list);
      treeEl.appendChild(catDiv);
    });

    if (term && totalMatches === 0) {
      const empty = document.createElement("div");
      empty.className = "no-results";
      empty.textContent = 'No pages match "' + filterText + '"';
      treeEl.appendChild(empty);
    }

    if (term) {
      searchMeta.textContent =
        matchedPageCount + " page" + (matchedPageCount === 1 ? "" : "s") + " found";
    } else {
      searchMeta.textContent = "";
    }
  }

  function highlightTerm(html, term) {
    if (!term) return html;
    // Only highlight within text nodes by operating on a temp container.
    const container = document.createElement("div");
    container.innerHTML = html;
    const walker = document.createTreeWalker(container, NodeFilter.SHOW_TEXT, null);
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp("(" + escaped + ")", "ig");
    const nodesToReplace = [];
    let node;
    while ((node = walker.nextNode())) {
      if (re.test(node.nodeValue)) nodesToReplace.push(node);
    }
    nodesToReplace.forEach((n) => {
      const span = document.createElement("span");
      span.innerHTML = n.nodeValue.replace(re, '<mark class="mark">$1</mark>');
      n.parentNode.replaceChild(span, n);
    });
    return container.innerHTML;
  }

  // Wraps bare /slash-command mentions in a .slash-cmd span so they render
  // colored even when they weren't hand-authored with the .badge-command
  // pill (e.g. inside <pre> diagrams or plain prose). Skips <h1> (already
  // styled via .badge-command) and anything already inside
  // .badge-command/.slash-cmd. Complete no-op when SLASH_COMMAND_RE is null,
  // i.e. whenever HELP_CONFIG.features.slashCommands is not enabled.
  function colorizeSlashCommands(root) {
    if (!SLASH_COMMAND_RE) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.nodeValue.includes("/")) return NodeFilter.FILTER_REJECT;
        let el = node.parentElement;
        while (el && el !== root) {
          if (
            el.tagName === "H1" ||
            el.classList.contains("badge-command") ||
            el.classList.contains("slash-cmd")
          ) {
            return NodeFilter.FILTER_REJECT;
          }
          el = el.parentElement;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodesToReplace = [];
    let node;
    while ((node = walker.nextNode())) {
      SLASH_COMMAND_RE.lastIndex = 0;
      if (SLASH_COMMAND_RE.test(node.nodeValue)) nodesToReplace.push(node);
    }
    nodesToReplace.forEach((n) => {
      SLASH_COMMAND_RE.lastIndex = 0;
      const span = document.createElement("span");
      span.innerHTML = n.nodeValue.replace(
        SLASH_COMMAND_RE,
        '<span class="slash-cmd">$1</span>'
      );
      n.parentNode.replaceChild(span, n);
    });
  }

  function renderDetail(key, highlightText) {
    const entry = PAGE_INDEX.get(key);
    if (!entry) return;
    const { cat, page } = entry;

    breadcrumbEl.innerHTML =
      cat.icon + " " + cat.label + " &nbsp;›&nbsp; " +
      '<span class="crumb-current">' + stripHtml(page.title) + "</span>";

    let html = page.html;
    if (highlightText) {
      html = highlightTerm(html, highlightText);
    }
    detailEl.innerHTML = html;
    colorizeSlashCommands(detailEl);
    detailEl.scrollTop = 0;

    // Wire up internal cross-links: <a data-goto="cat:page">
    detailEl.querySelectorAll("a[data-goto]").forEach((a) => {
      a.addEventListener("click", (e) => {
        e.preventDefault();
        navigateTo(a.dataset.goto, "");
        searchInput.value = "";
        searchClear.classList.remove("visible");
        buildTree("");
      });
    });

    // Wire up in-page anchor links (a TOC linking to "#some-heading-id"),
    // e.g. <a href="#installing">Installing</a> pointing at <h2 id="installing">.
    //
    // These are intentionally handled separately from a[data-goto] above, and
    // the selector below excludes any element that also has data-goto: if an
    // element somehow carries both attributes, data-goto wins (cross-topic
    // navigation is treated as the "real" intent; scrolling to an anchor is
    // just a same-page convenience on top of whatever data-goto already
    // does). Excluding data-goto elements here means the two handlers can
    // never both attach to — or both fire for — the same element.
    //
    // Why not just let the browser handle "#id" natively? Routing here is
    // driven entirely by location.hash (see loadFromHash/navigateTo below,
    // and the hashchange listener at the bottom of this file), which is
    // always of the form "#p=cat%3Apage". A plain <a href="#some-heading">
    // click would let the browser overwrite location.hash with
    // "#some-heading", silently breaking that scheme: nothing looks wrong
    // until the page is reloaded or the URL is shared, at which point
    // loadFromHash()'s `p=` regex no longer matches and navigation falls
    // through to defaultTopic, silently dropping the user off the topic
    // they were just reading. So this handler preventDefault()s unconditionally
    // and scrolls manually instead, leaving location.hash untouched.
    detailEl.querySelectorAll('a[href^="#"]:not([data-goto])').forEach((a) => {
      a.addEventListener("click", (e) => {
        e.preventDefault();
        const id = a.getAttribute("href").slice(1);
        if (!id) return;
        let target = null;
        try {
          target = detailEl.querySelector("#" + CSS.escape(id));
        } catch (err) {
          target = null;
        }
        // Missing target: do nothing visible (no error, no blanked pane) —
        // per spec, a dangling anchor link must be a silent no-op.
        if (target) target.scrollIntoView({ behavior: "smooth", block: "start" });
      });
    });
  }

  function navigateTo(key, term) {
    if (!PAGE_INDEX.has(key)) return;
    currentKey = key;
    location.hash = "p=" + encodeURIComponent(key);
    renderDetail(key, term);
    // update active state in tree without a full rebuild flash
    document.querySelectorAll(".page-item").forEach((el) => {
      el.classList.toggle("active", el.dataset.key === key);
    });
  }

  function loadFromHash() {
    const m = /p=([^&]+)/.exec(location.hash);
    if (m) {
      const key = decodeURIComponent(m[1]);
      if (PAGE_INDEX.has(key)) return key;
    }
    return null;
  }

  function firstAvailableKey() {
    const firstCat = HELP_CATEGORIES[0];
    if (firstCat && firstCat.pages[0]) return firstCat.id + ":" + firstCat.pages[0].id;
    return null;
  }

  // ---- Context-sensitivity ----
  // A host page can deep-link into help with `?ctx=some-id`, which is looked
  // up in HELP_CONFIG.contextMap. Precedence, highest first:
  //   1. #p=cat:page   (explicit hash always wins, including on back/forward)
  //   2. ?ctx=some-id  (mapped via contextMap)
  //   3. HELP_CONFIG.defaultTopic
  //   4. the very first page in HELP_CATEGORIES (last-resort fallback)
  // An unresolvable key at any stage falls through to the next one silently
  // — the page must never end up blank.
  function resolveContextKey(ctxId) {
    if (!ctxId) return null;
    const mapped = CONFIG.contextMap && CONFIG.contextMap[ctxId];
    if (mapped && PAGE_INDEX.has(mapped)) return mapped;
    return null;
  }

  function resolveInitialKey() {
    const fromHash = loadFromHash();
    if (fromHash) return fromHash;

    const ctxId = new URLSearchParams(location.search).get("ctx");
    const fromCtx = resolveContextKey(ctxId);
    if (fromCtx) return fromCtx;

    if (CONFIG.defaultTopic && PAGE_INDEX.has(CONFIG.defaultTopic)) {
      return CONFIG.defaultTopic;
    }

    return firstAvailableKey();
  }

  function expandCategoryFor(key) {
    if (!key) return;
    const catId = key.split(":")[0];
    collapsedCategories.delete(catId);
  }

  // ---- Search wiring ----
  let searchDebounce = null;
  searchInput.addEventListener("input", () => {
    const val = searchInput.value;
    searchClear.classList.toggle("visible", val.length > 0);
    clearTimeout(searchDebounce);
    searchDebounce = setTimeout(() => buildTree(val), 80);
  });

  searchClear.addEventListener("click", () => {
    searchInput.value = "";
    searchClear.classList.remove("visible");
    buildTree("");
    searchInput.focus();
  });

  searchInput.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
      searchInput.value = "";
      searchClear.classList.remove("visible");
      buildTree("");
    }
  });

  // ---- Splitter (drag + keyboard resize of the explorer panel) ----

  // Namespaced so multiple generated help sites (e.g. several projects
  // opened from the same browser profile via file://) don't clobber each
  // other's saved width. Previously this was a single hard-coded key.
  const EXPLORER_WIDTH_KEY = (CONFIG.storageKey || "help") + "-explorer-width";

  // Width geometry has exactly one source of truth: the CSS custom
  // properties on :root. Previously the CSS (min 160 / max 480) and this
  // file's own fallback constants (min 220 / max 720) disagreed; reading
  // them from getComputedStyle means CSS is always authoritative and the
  // numbers can never drift apart again.
  function cssPx(varName, fallback) {
    const raw = getComputedStyle(document.documentElement)
      .getPropertyValue(varName)
      .trim();
    const n = parseInt(raw, 10);
    return Number.isFinite(n) ? n : fallback;
  }
  const WIDTH_DEFAULT = cssPx("--explorer-width-default", 220);
  const WIDTH_MIN = cssPx("--explorer-width-min", 160);
  const WIDTH_MAX = cssPx("--explorer-width-max", 480);

  function getStoredWidth() {
    try {
      const stored = localStorage.getItem(EXPLORER_WIDTH_KEY);
      return stored ? parseInt(stored, 10) : null;
    } catch (e) {
      return null; // localStorage throws under file:// in some browsers
    }
  }

  function storeWidth(px) {
    try {
      localStorage.setItem(EXPLORER_WIDTH_KEY, String(px));
    } catch (e) {
      /* ignore — file:// origin or storage disabled */
    }
  }

  function setWidth(px) {
    const clamped = Math.min(WIDTH_MAX, Math.max(WIDTH_MIN, px));
    explorerEl.style.width = clamped + "px";
    splitterEl.setAttribute("aria-valuenow", String(Math.round(clamped)));
    return clamped;
  }

  const storedWidth = getStoredWidth();
  setWidth(storedWidth || WIDTH_DEFAULT);
  splitterEl.setAttribute("aria-valuemin", String(WIDTH_MIN));
  splitterEl.setAttribute("aria-valuemax", String(WIDTH_MAX));

  let dragging = false;

  splitterEl.addEventListener("mousedown", (e) => {
    dragging = true;
    splitterEl.classList.add("dragging");
    document.body.classList.add("resizing");
    e.preventDefault();
  });

  // Bound to window rather than the 5px splitter element itself: once a drag
  // starts, the cursor routinely moves faster than the handle and ends up
  // outside its bounding box. Binding mousemove/mouseup to window means the
  // drag keeps tracking correctly no matter how far the pointer strays.
  window.addEventListener("mousemove", (e) => {
    if (!dragging) return;
    // Width comes directly from clientX because the explorer is pinned to
    // the left edge of the viewport — clientX IS the distance from that
    // edge, no offset math required.
    setWidth(e.clientX);
  });

  window.addEventListener("mouseup", () => {
    if (!dragging) return;
    dragging = false;
    splitterEl.classList.remove("dragging");
    document.body.classList.remove("resizing");
    storeWidth(explorerEl.getBoundingClientRect().width);
  });

  splitterEl.addEventListener("dblclick", () => {
    setWidth(WIDTH_DEFAULT);
    storeWidth(WIDTH_DEFAULT);
  });

  // Keyboard access: Left/Right resize by 16px, Shift+Left/Right by 48px,
  // Home/End jump to min/max, Enter resets to the default width.
  splitterEl.addEventListener("keydown", (e) => {
    const current = explorerEl.getBoundingClientRect().width;
    const step = e.shiftKey ? 48 : 16;
    let next = null;
    switch (e.key) {
      case "ArrowLeft":
        next = current - step;
        break;
      case "ArrowRight":
        next = current + step;
        break;
      case "Home":
        next = WIDTH_MIN;
        break;
      case "End":
        next = WIDTH_MAX;
        break;
      case "Enter":
        next = WIDTH_DEFAULT;
        break;
      default:
        return;
    }
    e.preventDefault();
    const applied = setWidth(next);
    storeWidth(applied);
  });

  // ---- Host API ----
  // Exposed so an embedding host (e.g. an iframe wrapper, or a desktop shell
  // that loads this page in a webview) can drive navigation programmatically
  // using the same addressing scheme as the UI itself.
  window.HelpSystem = {
    open: function (topicKey) {
      if (PAGE_INDEX.has(topicKey)) {
        navigateTo(topicKey, "");
        expandCategoryFor(topicKey);
        buildTree(searchInput.value);
      } else if (CONFIG.defaultTopic && PAGE_INDEX.has(CONFIG.defaultTopic)) {
        // Unknown topic key: fall back rather than leaving the page blank.
        navigateTo(CONFIG.defaultTopic, "");
        expandCategoryFor(CONFIG.defaultTopic);
        buildTree(searchInput.value);
      }
    },
    openForContext: function (ctxId) {
      const key = resolveContextKey(ctxId) ||
        (CONFIG.defaultTopic && PAGE_INDEX.has(CONFIG.defaultTopic) ? CONFIG.defaultTopic : null) ||
        firstAvailableKey();
      if (key) {
        navigateTo(key, "");
        expandCategoryFor(key);
        buildTree(searchInput.value);
      }
    },
    // No-op in standalone mode (there is nothing to "close" — this page IS
    // the window). Exists purely so embedding hosts can call
    // window.HelpSystem.close() uniformly regardless of which mode the help
    // system happens to be running in. Dispatches an event so an embedding
    // host CAN hook it (e.g. to hide an iframe) without this file needing to
    // know anything about that host.
    close: function () {
      window.dispatchEvent(new CustomEvent("helpsystem:close"));
    },
  };

  // ---- Init ----
  const initialKey = resolveInitialKey();
  currentKey = initialKey;
  expandCategoryFor(initialKey);
  buildTree("");
  if (initialKey) renderDetail(initialKey, "");
  document.querySelectorAll(".page-item").forEach((el) => {
    el.classList.toggle("active", el.dataset.key === initialKey);
  });

  window.addEventListener("hashchange", () => {
    const key = loadFromHash();
    if (key && key !== currentKey) {
      currentKey = key;
      renderDetail(key, "");
      document.querySelectorAll(".page-item").forEach((el) => {
        el.classList.toggle("active", el.dataset.key === key);
      });
    }
  });
})();
